const ACTIVE_SUFFIX = " — Active Players";

function listTitle(title: string): string {
  const active = title.endsWith(ACTIVE_SUFFIX);
  const base = active ? title.slice(0, -ACTIVE_SUFFIX.length) : title;
  const translated = LIST_TITLES[base];
  // Unknown list (new seed): keep the data set's English title rather than guess.
  if (!translated) return title;
  return active ? `${translated} — Aktif Oyuncular` : translated;
}

